# 2. Build one merged response matrix
# ==============================================================================

# Item names are prefixed with their source table. The scout requires disjoint
# items, but the prefix keeps that from being load-bearing and gives the
# block-ordered heatmap its provenance.
build_merged <- function(tables) {
  parts <- map(tables, function(tbl) {
    df <- tryCatch(irw_fetch(tbl), error = function(e) {
      message("    fetch failed for ", tbl, ": ", conditionMessage(e))
      NULL
    })
    if (is.null(df)) return(NULL)
    df$item         <- paste0(tbl, "::", df$item)
    df$source_table <- tbl
    df[, c("id", "item", "resp", "source_table")]
  })
  parts <- compact(parts)
  if (length(parts) < 2) return(NULL)

  # Restrict to respondents present in every member table, so the merged matrix
  # is a complete battery rather than a block-diagonal patchwork.
  shared <- reduce(map(parts, function(p) unique(na.omit(p$id))), intersect)
  if (length(shared) < 100) {
    message("    skipped: only ", length(shared), " shared respondents")
    return(NULL)
  }
  if (length(shared) > MAX_N) shared <- sample(shared, MAX_N)

  long <- bind_rows(parts)
  long <- long[long$id %in% shared, ]

  resp <- irw_long2resp(long[, c("id", "item", "resp")])
  resp$id <- NULL
  resp <- resp[, sapply(resp, function(x) length(unique(na.omit(x))) > 1), drop = FALSE]

  # irw_long2resp() prefixes every column with "item_", so the source table has
  # to be recovered from the column names rather than joined against the long
  # data. Column names look like "item_<source table>::<item>".
  item_source <- tibble(
    item         = names(resp),
    source_table = sub("::.*$", "", sub("^item_", "", names(resp)))
  )

  list(
    resp        = resp,
    item_source = item_source,
    n_shared    = length(shared),
    n_tables    = length(parts),
    tables      = map_chr(parts, function(p) p$source_table[1])
  )
}

# ==============================================================================
# 3. Same diagnostics as the single-table pass
# ==============================================================================

fit_merged <- function(group) {
  message("  Processing merge group: ", group$anchor, " (k = ", length(group$tables), ")")

  m <- build_merged(group$tables)
  if (is.null(m) || ncol(m$resp) < MIN_ITEMS) return(NULL)
  resp <- m$resp

  n_categories <- length(unique(na.omit(unlist(resp))))

  if (n_categories == 2) {
    cor_method <- "tetrachoric"
    cormat <- tryCatch(suppressWarnings(suppressMessages(psych::tetrachoric(resp)$rho)),
                       error = function(e) { message("    tetrachoric failed: ", conditionMessage(e)); NULL })
  } else if (n_categories >= 3 && n_categories <= 10) {
    cor_method <- "polychoric"
    # Merged batteries routinely stack instruments with different scale lengths
    # (a 5-point scale beside a 6-point one), which leaves sparse cells in the
    # bivariate tables. psych's default continuity correction (0.5) can then
    # push polycor into an unusable matrix -- psych's own advice in that case
    # is correct = 0, so retry that way before giving up.
    poly <- function(correct) tryCatch(
      suppressWarnings(suppressMessages(
        psych::polychoric(resp, max.cat = 10, correct = correct, progress = FALSE)$rho
      )),
      error = function(e) { message("    polychoric (correct = ", correct, ") failed: ",
                                    conditionMessage(e)); NULL }
    )
    cormat <- poly(0.5)
    if (is.null(cormat) || anyNA(cormat)) {
      message("    retrying polychoric with correct = 0")
      retry <- poly(0)
      if (!is.null(retry) && !anyNA(retry)) {
        cormat     <- retry
        cor_method <- "polychoric (correct = 0)"
      }
    }
  } else {
    cor_method <- "pearson"
    message("    n_categories = ", n_categories, " outside 2-10; falling back to Pearson correlations")
    cormat <- tryCatch(cor(resp, use = "pairwise.complete.obs"),
                       error = function(e) { message("    Pearson failed: ", conditionMessage(e)); NULL })
  }
  if (is.null(cormat) || anyNA(cormat)) {
    message("    skipped: correlation matrix unusable")
    return(NULL)
  }

  ev <- tryCatch(eigen(cormat, symmetric = TRUE, only.values = TRUE)$values, error = function(e) NULL)
  if (is.null(ev) || length(ev) < 2) {
    message("    skipped: eigen decomposition failed")
    return(NULL)
  }

  pa <- tryCatch(psych::fa.parallel(cormat, n.obs = nrow(resp), fa = "fa", plot = FALSE),
                 error = function(e) { message("    fa.parallel failed: ", conditionMessage(e)); NULL })

  list(
    summary = tibble(
      anchor          = group$anchor,
      n_tables        = m$n_tables,
      n_items         = ncol(resp),
      n_participants  = nrow(resp),
      n_categories    = n_categories,
      cor_method      = cor_method,
      ratio_12        = ev[1] / ev[2],
      prop_var_1      = ev[1] / sum(ev),
      nfact_suggested = if (!is.null(pa)) pa$nfact else NA_integer_,
      tables          = paste(m$tables, collapse = "|")
    ),
    eigenvalues = ev,
    # Kept for the block-ordered heatmap: full matrix only where it is small
    # enough to be worth carrying in the cache.
    cormat      = if (ncol(cormat) <= 150) cormat else NULL,
    item_source = m$item_source
  )
}

# ==============================================================================
# 4. Run, writing each group to disk as it completes
# ==============================================================================

fit_to_disk <- function(group) {
  out_file <- file.path(fits_dir, paste0(group$anchor, ".rds"))
  if (file.exists(out_file)) {
    message("  Skipping (already done): ", group$anchor)
    return(invisible(NULL))
  }
  result <- tryCatch(fit_merged(group), error = function(e) {
    message("    unexpected error for ", group$anchor, ": ", conditionMessage(e))
    NULL
  })
  if (!is.null(result)) saveRDS(result, out_file)
}

plan(multisession, workers = min(4, parallel::detectCores() %/% 2))
message("\nAnalyzing ", length(MERGE_GROUPS), " merge groups...")
future_map(MERGE_GROUPS, fit_to_disk, .options = furrr_options(seed = TRUE))
plan(sequential)

