# dimensionality_merge_compute.R
#
# Companion to dimensionality_compute.R. That script asks how often a single
# IRW table looks unidimensional; this one asks what happens at the other end
# of the scale -- when several distinct instruments given to the same
# respondents are stacked into one wide matrix.
#
# IRW tables are typically one instrument each, which caps how multidimensional
# any single table can be. Tables sharing a DOI are usually several instruments
# from one study administered to one cohort, so merging them recovers the full
# battery a respondent actually saw. That is where genuinely high-dimensional
# structure lives in the warehouse.
#
# The number of member tables (k) is an INDEX of how many instruments were
# stacked, not a ground-truth factor count: some groups split one inventory
# into per-subscale tables, others repeat a construct pre/post. The question
# here is how multidimensional merged batteries get and whether the two
# diagnostics track that, not whether either recovers a known k.
#
# Groups are frozen in MERGE_GROUPS below rather than discovered at run time.
# See dimensionality_merge_scout.R for how they were found, and why the frozen
# list is preferred over calling irw_merge() directly.
#
# Output: dimensionality_data/dimensionality_merge_results.rds
#
# Usage:
#   Rscript vignettes/dimensionality_merge_compute.R   # from project root

